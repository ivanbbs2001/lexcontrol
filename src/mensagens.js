/* Ordem embaralhada de forma determinística (sem repetir antes de esgotar todas),
   mesma mensagem para o dia inteiro. */
function ordem(n) {
  let s = 2463534242;
  const rnd = () => { s ^= s << 13; s >>>= 0; s ^= s >>> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; };
  const a = Array.from({ length: n }, (_, i) => i);
  for (let i = n - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}
const ORDEM = ordem(MENSAGENS.length);

export function mensagemDoDia(d = new Date()) {
  const dias = Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 86400000);
  return MENSAGENS[ORDEM[dias % MENSAGENS.length]];
}
